"""The committed baseline world (span=union__case=A), regenerated with the vectorised engine.

Item 12 of the v2 plan. The world's null was generated by
scripts/run_null_local.py (seed 42; exact enumeration for 328, 398, 454,
917; 10,000 sampled permutations otherwise) and summarised by
aggregate.py --local under every summary spec. The two null parquets are
git-ignored (80 MB); everything derived from them is committed and the
generation is deterministic, which ``test_regenerating_a_patient_reproduces_the_committed_summary``
checks without the parquets.
"""

