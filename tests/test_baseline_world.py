def test_baseline_config_records_engine_and_exact_modes(baseline_dir):
    cfg = read_world_config(BASELINE)
    assert cfg["world_id"] == "span=union__case=A" and cfg["null_engine"] == "vectorised"
    modes = {int(k): v for k, v in cfg["null_modes"].items()}
    for pid, n in EXACT_PATIENTS.items():
        assert modes[pid] == {"mode": "exact", "n_permutations": n}
    assert all(v["mode"] == "sampled" and v["n_permutations"] == 10000 and v["seed"] == 42
               for pid, v in modes.items() if pid not in EXACT_PATIENTS)


def test_baseline_summary_has_every_spec(summary):
    assert {sp.key for sp in available_specs(summary)} == {sp.key for sp in ALL_SPECS}
    assert sorted(summary["patient_id"].unique()) == V1_ASSESSED
    for pid, n in EXACT_PATIENTS.items():
        assert (summary[summary.patient_id == pid]["n_permutations"] == n).all()


def test_baseline_summary_yields_the_primary_sets(summary):
    sets = derive_concordant_sets(summary)
    assert sets[PRIMARY.key] == BASELINE_CONCORDANT_MEAN
    assert sets[SummarySpec("effective", "spearman", "median").key] == BASELINE_CONCORDANT_MEDIAN
    # all/spearman on the regenerated null agrees with the centred rule on the v1 null
    assert sets[V1_SPEC.key] == V1_CONCORDANT_MEAN
    assert sets[SummarySpec("all", "spearman", "median").key] == V1_CONCORDANT_MEDIAN


def test_generated_concordant_sets_file_matches_summary(summary):
    sets = json.loads(concordant_sets_path().read_text())["span=union__case=A"]
    assert sets == derive_concordant_sets(summary)
    assert "span=union__case=A" in list_worlds()


def test_no_leaked_perfect_correlations_in_the_regenerated_summary(summary):
    """The v1 null had |Z| ~ 18 leaks for 328/398/454/917; the engine records those as invalid."""
    assert summary["null_mean"].abs().max() < 1.5
    s398 = select(summary, V1_SPEC).set_index("patient_id").loc[398]
    assert -0.4 < s398["null_mean"] < -0.1  # was -1.45 on the v1 null


