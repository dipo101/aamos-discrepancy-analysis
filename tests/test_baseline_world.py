def test_baseline_observed_and_sweep_files_exist(baseline_dir):
    observed = pd.read_csv(baseline_dir / "observed.csv")
    assert set(observed["config_set"]) == {"all", "effective"} and set(observed["correlation_type"]) == {"spearman", "pearson"}
    eff = observed[(observed.config_set == "effective") & (observed.correlation_type == "spearman") & (observed.measure == "mean")].set_index("patient_id")
    assert (eff["n_valid_configs_observed"] <= 60).all()
    assert eff.loc[473, "observed_z"] == pytest.approx(0.432, abs=5e-4)
    sweep = pd.read_csv(baseline_dir / "threshold_sweep.csv")
    row = sweep[(sweep.config_set == "effective") & (sweep.correlation_type == "spearman") & (sweep.measure == "mean")].set_index("threshold")["concordant"]
    assert row.loc[0.5] == "702 917" and row.loc[0.75] == "917" and row.loc[0.9] == "917"


@pytest.mark.parametrize("patient_id", [917, 454])
def test_regenerating_a_patient_reproduces_the_committed_summary(data_dir, summary, patient_id):
    """Determinism without the 80 MB parquet: regenerate one exact-enumeration patient and re-derive its rows."""
    from aamos_concordance.summary import observed_statistics, permutation_p_values
    q = pd.read_csv(data_dir / "anonym_aamos00_dailyquestionnaire_dt.csv")
    inh = pd.read_csv(data_dir / "anonym_aamos00_smartinhaler_dt.csv")
    qq, ii = q[q.user_key == patient_id], inh[inh.user_key == patient_id]
    pc = run_patient_exact(patient_id, qq, ii)
    per_config = pd.read_csv(world_dir(BASELINE) / PER_CONFIG_Z)
    for spec in (PRIMARY, V1_SPEC, SummarySpec("all", "pearson", "median")):
        null = null_from_per_config(pc, correlation_type=spec.correlation_type, config_indices=spec.config_indices)
        obs = observed_statistics(per_config, f"{spec.correlation_type}_z", spec.config_indices).set_index("patient_id")
        row = permutation_p_values(obs[spec.measure], null, null_column=f"null_{spec.measure}_z",
                                   n_patients=15).set_index("patient_id").loc[patient_id]
        committed = select(summary, spec).set_index("patient_id").loc[patient_id]
        for col in ("observed_z", "p_value", "null_mean", "null_std", "n_permutations", "n_ties_at_observed"):
            assert row[col] == pytest.approx(committed[col], abs=1e-9), (spec.key, col)
